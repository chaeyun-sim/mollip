  "weekdayClose" = nullif(sh.weekday_close, '00:00'),
  "weekendOpen" = nullif(sh.weekend_open, '00:00'),
  "weekendClose" = nullif(sh.weekend_close, '00:00'),
  "rstdeInfo" = coalesce(m.holiday, nullif(sh.rest_info, ''))
