-- "HH:MM" 패턴 두 개를 순서대로 뽑아 평일 시간으로 best-effort 채운다.
update public.museums m
set
  "weekdayOpen" = coalesce("weekdayOpen", (regexp_match(open_hours, '(\d{1,2}:\d{2})\D+(\d{1,2}:\d{2})'))[1]),
  "weekdayClose" = coalesce("weekdayClose", (regexp_match(open_hours, '(\d{1,2}:\d{2})\D+(\d{1,2}:\d{2})'))[2]),
  "rstdeInfo" = coalesce("rstdeInfo", holiday)
where "weekdayOpen" is null and open_hours is not null;
